CREATE OR REPLACE TABLE DEV_MT_BIG_BETS_DB.POC.RCA_ANALYSIS_CHATS_JULY_SEPT_Pred_and_Grading_Results_v1_test
AS
SELECT
    inputt.DIARIZED_TRANSCRIPT_TEXT,
    inputt.call_id AS transcript_id,
    pred.*   EXCLUDE (call_id),
    grades.* EXCLUDE (call_id)
