JOIN DEV_MT_BIG_BETS_DB.POC.CHAT_ANALYSIS_TAXONOMY_V9_CD_GRADE_CALLS AS grades
  ON inputt.call_id = grades.call_id
JOIN DEV_MT_BIG_BETS_DB.POC.CALL_ANALYSIS_TAXONOMY_V1 AS pred
  ON inputt.call_id = pred.call_id
ORDER BY transcript_id;

