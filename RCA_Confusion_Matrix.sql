CREATE OR REPLACE TABLE DEV_MT_BIG_BETS_DB.POC.RCA_ANALYSIS_CHATS_CM_CT_v1_test
AS
SELECT
  TRANSCRIPT_ID,
  CONTACT_TYPE AS PREDICTED_CONTACT_TYPE,
  COALESCE(NULLIF(CONTACT_TYPE_SUGGESTED_LABEL,''), CONTACT_TYPE) AS ACTUAL_CONTACT_TYPE,
  CONTACT_TYPE_VERDICT,
  CONTACT_TYPE_SCORE,
  IS_NO_INPUT
FROM DEV_MT_BIG_BETS_DB.POC.RCA_ANALYSIS_CHATS_JULY_SEPT_Pred_and_Grading_Results_v1_test
;


--Recall and Precision - CT
WITH base AS (
  SELECT
    ACTUAL_CONTACT_TYPE   AS ACTUAL,
    PREDICTED_CONTACT_TYPE AS PREDICTED
  FROM DEV_MT_BIG_BETS_DB.POC.RCA_ANALYSIS_CHATS_CM_CT_v1_test
),
labels AS (
  SELECT ACTUAL AS LABEL FROM base
  UNION
  SELECT PREDICTED FROM base
),
counts AS (
  SELECT
    l.LABEL,
    SUM(IFF(b.ACTUAL = l.LABEL AND b.PREDICTED = l.LABEL, 1, 0)) AS TP,
    SUM(IFF(b.ACTUAL <> l.LABEL AND b.PREDICTED = l.LABEL, 1, 0)) AS FP,
    SUM(IFF(b.ACTUAL = l.LABEL AND b.PREDICTED <> l.LABEL, 1, 0)) AS FN,
    SUM(IFF(b.ACTUAL = l.LABEL, 1, 0)) AS SUPPORT
  FROM labels l
  CROSS JOIN base b
  GROUP BY 1
),
metrics AS (
  SELECT
    LABEL,
    SUPPORT,
    TP, FP, FN,
    TP / NULLIF((TP + FP), 0)::FLOAT AS PRECISION,
    TP / NULLIF((TP + FN), 0)::FLOAT AS RECALL,
    (2*TP) / NULLIF((2*TP + FP + FN), 0)::FLOAT AS F1
  FROM counts
)
SELECT *
FROM metrics
ORDER BY SUPPORT DESC, LABEL;


